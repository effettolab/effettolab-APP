create or replace function public.track_order_technician_assignment()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if TG_OP='INSERT' or NEW.technician_id is distinct from OLD.technician_id then
    if NEW.technician_id is null then
      NEW.technician_assigned_at := null;
      NEW.technician_assigned_by := null;
    else
      NEW.technician_assigned_at := now();
      NEW.technician_assigned_by := auth.uid();
    end if;
  end if;
  return NEW;
end;
$$;
drop trigger if exists trg_track_order_technician_assignment on public.orders;
create trigger trg_track_order_technician_assignment
before insert or update of technician_id on public.orders
for each row execute function public.track_order_technician_assignment();

