-- Costos unitarios fotografiados al momento de ingresar la línea.
-- No se reconstruyen costos anteriores porque no hay historial confiable.
create table if not exists public.cost_snapshots (
  source_type text not null check (source_type in ('order_item','invoice_item')),
  source_item_id bigint not null,
  stock_id bigint references public.stock(id) on delete set null,
  unit_cost numeric(12,2) not null check (unit_cost>=0),
  captured_at timestamptz not null default now(),
  primary key (source_type,source_item_id)
);
create index if not exists cost_snapshots_stock_id_idx on public.cost_snapshots(stock_id);
alter table public.cost_snapshots enable row level security;
grant select on public.cost_snapshots to authenticated;
drop policy if exists cost_snapshots_finance_select on public.cost_snapshots;
create policy cost_snapshots_finance_select on public.cost_snapshots
for select to authenticated using (public.has_perm('$'));

create or replace function public.capture_order_item_cost_snapshot()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare v_cost numeric(12,2);
begin
  if NEW.kind='Producto' and NEW.stock_id is not null then
    select sc.cost into v_cost
    from public.stock s
    join public.stock_costs sc on sc.stock_id=s.id
    where s.id=NEW.stock_id
      and coalesce(s.ownership_type,'Propio')='Propio';
    if v_cost is not null then
      insert into public.cost_snapshots(source_type,source_item_id,stock_id,unit_cost)
      values('order_item',NEW.id,NEW.stock_id,round(v_cost,2))
      on conflict (source_type,source_item_id) do nothing;
    end if;
  end if;
  return NEW;
end;
$$;
revoke all on function public.capture_order_item_cost_snapshot() from public, anon, authenticated;
drop trigger if exists trg_capture_order_item_cost_snapshot on public.order_items;
create trigger trg_capture_order_item_cost_snapshot
after insert on public.order_items
for each row execute function public.capture_order_item_cost_snapshot();

create or replace function public.capture_invoice_item_cost_snapshot()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_invoice_kind text;
  v_cost numeric(12,2);
begin
  select i.kind into v_invoice_kind
  from public.invoices i where i.id=NEW.invoice_id;
  if v_invoice_kind='Factura' and NEW.kind='Producto' and NEW.stock_id is not null then
    if NEW.order_item_id is not null then
      select cs.unit_cost into v_cost
      from public.cost_snapshots cs
      where cs.source_type='order_item' and cs.source_item_id=NEW.order_item_id;
    end if;
    if v_cost is null then
      select sc.cost into v_cost
      from public.stock s
      join public.stock_costs sc on sc.stock_id=s.id
      where s.id=NEW.stock_id
        and coalesce(s.ownership_type,'Propio')='Propio';
    end if;
    if v_cost is not null then
      insert into public.cost_snapshots(source_type,source_item_id,stock_id,unit_cost)
      values('invoice_item',NEW.id,NEW.stock_id,round(v_cost,2))
      on conflict (source_type,source_item_id) do nothing;
    end if;
  end if;
  return NEW;
end;
$$;
revoke all on function public.capture_invoice_item_cost_snapshot() from public, anon, authenticated;
drop trigger if exists trg_capture_invoice_item_cost_snapshot on public.invoice_items;
create trigger trg_capture_invoice_item_cost_snapshot
after insert on public.invoice_items
for each row execute function public.capture_invoice_item_cost_snapshot();

create or replace function public.capture_quote_costs_when_invoiced()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare r record; v_cost numeric(12,2);
begin
  if OLD.kind='Cotización' and NEW.kind='Factura' then
    for r in
      select ii.id,ii.stock_id,ii.kind,ii.order_item_id,
             coalesce(s.ownership_type,'Propio') as ownership_type
      from public.invoice_items ii
      left join public.stock s on s.id=ii.stock_id
      where ii.invoice_id=NEW.id and ii.kind='Producto' and ii.stock_id is not null
    loop
      v_cost := null;
      if r.order_item_id is not null then
        select cs.unit_cost into v_cost
        from public.cost_snapshots cs
        where cs.source_type='order_item' and cs.source_item_id=r.order_item_id;
      end if;
      if v_cost is null and r.ownership_type='Propio' then
        select sc.cost into v_cost from public.stock_costs sc where sc.stock_id=r.stock_id;
      end if;
      if v_cost is not null then
        insert into public.cost_snapshots(source_type,source_item_id,stock_id,unit_cost)
        values('invoice_item',r.id,r.stock_id,round(v_cost,2))
        on conflict (source_type,source_item_id) do nothing;
      end if;
    end loop;
  end if;
  return NEW;
end;
$$;
revoke all on function public.capture_quote_costs_when_invoiced() from public, anon, authenticated;
drop trigger if exists trg_capture_quote_costs_when_invoiced on public.invoices;
create trigger trg_capture_quote_costs_when_invoiced
after update of kind on public.invoices
for each row execute function public.capture_quote_costs_when_invoiced();

-- Comisiones comerciales: registro por vendedor, independiente del pago técnico.
-- No se asignan porcentajes ni importes automáticamente.
create table if not exists public.sales_commissions (
  id bigint generated by default as identity primary key,
  invoice_id bigint not null unique references public.invoices(id) on delete cascade,
  salesperson_id uuid not null references public.profiles(id),
  sale_amount numeric(12,2) not null default 0 check (sale_amount>=0),
  commission_rate numeric(5,2),
  commission_amount numeric(12,2),
  status text not null default 'Por definir'
    check (status in ('Por definir','Pendiente','Pagada','Anulada')),
  paid_on date,
  paid_method text,
  paid_by uuid references auth.users(id) on delete set null,
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint sales_commission_rate_check check (commission_rate is null or commission_rate between 0 and 100),
  constraint sales_commission_amount_check check (commission_amount is null or commission_amount>=0)
);
create index if not exists sales_commissions_salesperson_status_idx
  on public.sales_commissions(salesperson_id,status,created_at desc);
alter table public.sales_commissions enable row level security;
grant select, update on public.sales_commissions to authenticated;
grant usage, select on sequence public.sales_commissions_id_seq to authenticated;
drop policy if exists sales_commissions_select_own_or_finance on public.sales_commissions;
create policy sales_commissions_select_own_or_finance on public.sales_commissions
for select to authenticated
using (salesperson_id=auth.uid() or public.has_perm('$'));
drop policy if exists sales_commissions_update_finance on public.sales_commissions;
create policy sales_commissions_update_finance on public.sales_commissions
for update to authenticated
using (public.has_perm('$'))
with check (public.has_perm('$'));

create or replace function public.sync_sales_commission(p_invoice_id bigint)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_kind text;
  v_seller uuid;
  v_total numeric(12,2);
begin
  select i.kind,i.salesperson_id into v_kind,v_seller
  from public.invoices i where i.id=p_invoice_id;
  if not found then return; end if;

  if v_kind='Factura' and v_seller is not null then
    select coalesce(sum(ii.qty*ii.unit_price),0)::numeric(12,2)
    into v_total
    from public.invoice_items ii where ii.invoice_id=p_invoice_id;

    insert into public.sales_commissions(invoice_id,salesperson_id,sale_amount,status)
    values(p_invoice_id,v_seller,v_total,'Por definir')
    on conflict (invoice_id) do update
      set salesperson_id=excluded.salesperson_id,
          sale_amount=excluded.sale_amount,
          status=case
            when public.sales_commissions.status='Anulada' then 'Por definir'
            else public.sales_commissions.status
          end,
          updated_at=now();
  else
    update public.sales_commissions
    set status=case when status='Pagada' then status else 'Anulada' end,
        updated_at=now()
    where invoice_id=p_invoice_id;
  end if;
end;
$$;
revoke all on function public.sync_sales_commission(bigint) from public, anon, authenticated;

create or replace function public.sync_sales_commission_from_invoice()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  perform public.sync_sales_commission(NEW.id);
